"""Pydantic message models. Draft: finalize together with the API spec (WP1, T1.3)."""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, Field

from cfl.protocol import PROTOCOL_VERSION


class RegisterRequest(BaseModel):
    client_id: str
    client_version: str
    protocol_version: str = PROTOCOL_VERSION


class RegisterResponse(BaseModel):
    accepted: bool
    reason: str | None = None


class TaskAssignment(BaseModel):
    run_id: str
    round_id: int
    model_version: int
    deadline: datetime
    config: dict = Field(default_factory=dict)


class UpdateMetadata(BaseModel):
    run_id: str
    round_id: int
    client_id: str
    update_id: str  # idempotency key generated by the client; retries reuse it
    model_version: int
    num_samples: int
    checksum_sha256: str
    metrics: dict[str, float] = Field(default_factory=dict)


class UpdateAck(BaseModel):
    accepted: bool
    reason: str | None = None  # e.g. "duplicate", "stale_round", "checksum_mismatch"
